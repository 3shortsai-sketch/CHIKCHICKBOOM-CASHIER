/**
 * Minimal .xlsx writer: no library needed, works offline.
 * An .xlsx file is a zip of a few XML files; we write them "stored"
 * (uncompressed), which every Excel / Google Sheets / LibreOffice opens.
 */

export type CellStyle = 'bold' | 'money' | 'boldMoney' | 'pct' | 'header' | 'title';
export type XCell = string | number | null | undefined | { v: string | number; s: CellStyle };
export type Sheet = {
  name: string;
  rows: XCell[][];
  /** Column widths in characters. */
  widths?: number[];
  /** Keep the first row visible while scrolling (for tables). */
  freezeHeader?: boolean;
};

// Style indexes in styles.xml below.
const STYLE: Record<CellStyle, number> = { bold: 1, money: 2, boldMoney: 3, pct: 4, header: 5, title: 6 };

function esc(s: string): string {
  return s
    .replace(/[\u0000-\u0008\u000B\u000C\u000E-\u001F￾￿]/g, '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

export function colName(i: number): string {
  let n = i + 1;
  let s = '';
  while (n > 0) {
    const m = (n - 1) % 26;
    s = String.fromCharCode(65 + m) + s;
    n = Math.floor((n - 1) / 26);
  }
  return s;
}

function cellXml(c: XCell, ref: string): string {
  if (c === null || c === undefined || c === '') return '';
  const v = typeof c === 'object' ? c.v : c;
  const st = typeof c === 'object' ? ` s="${STYLE[c.s]}"` : '';
  if (typeof v === 'number' && Number.isFinite(v)) return `<c r="${ref}"${st}><v>${v}</v></c>`;
  return `<c r="${ref}"${st} t="inlineStr"><is><t xml:space="preserve">${esc(String(v))}</t></is></c>`;
}

function sheetXml(sh: Sheet): string {
  const cols = sh.widths?.length ? `<cols>${sh.widths.map((w, i) => `<col min="${i + 1}" max="${i + 1}" width="${w}" customWidth="1"/>`).join('')}</cols>` : '';
  const view = sh.freezeHeader
    ? '<sheetViews><sheetView workbookViewId="0"><pane ySplit="1" topLeftCell="A2" activePane="bottomLeft" state="frozen"/></sheetView></sheetViews>'
    : '<sheetViews><sheetView workbookViewId="0"/></sheetViews>';
  const rows = sh.rows
    .map((r, ri) => `<row r="${ri + 1}">${r.map((c, ci) => cellXml(c, `${colName(ci)}${ri + 1}`)).join('')}</row>`)
    .join('');
  return `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main">${view}${cols}<sheetData>${rows}</sheetData></worksheet>`;
}

